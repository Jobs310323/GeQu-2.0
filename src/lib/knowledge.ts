export const ARTICLES_BY_CATEGORY = (id: string) => ARTICLES.filter(a => a.category === id);

export function searchArticles(query: string): Article[] {
    const q = query.trim().toLowerCase();
    if (!q) return [];
    return ARTICLES.filter(a =>
        a.title.toLowerCase().includes(q) ||
        a.summary.toLowerCase().includes(q) ||
        a.body.toLowerCase().includes(q));
}

/** Other articles in the same category, for the "read next" row. */
export function relatedTo(article: Article, limit = 3): Article[] {
    return ARTICLES.filter(a => a.category === article.category && a.id !== article.id).slice(0, limit);
}
